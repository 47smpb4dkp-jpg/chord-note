#!/usr/bin/env python3
# テストの出力から「毎回変わるのが当たり前のもの」だけを伏せる。
# ここに足す regexp は慎重に。伏せすぎると、本当の間違いも見えなくなる。
# 2026-11-24 に40本を2回流して実測し、変わったのは下の5種類だけだった。
import re, sys

RULES = [
    # 時刻（ISO・スラッシュ区切り・短い形）
    (r'20\d\d-\d\d-\d\dT\d\d:\d\d:\d\d(?:\.\d+)?Z', '<ISO時刻>'),
    (r'20\d\d/\d\d/\d\d \d{1,2}:\d\d:\d\d',          '<日時>'),
    (r'20\d\d/\d\d/\d\d \d{1,2}:\d\d',               '<日時>'),
    (r'(?<!\d)\d{1,2}/\d{1,2} \d{1,2}:\d\d(?!\d)',   '<日時>'),
    # アプリの版（デプロイごとに変わる）
    (r'\bV\d{6}-\d{2}[a-z]*\b',                      '<版>'),
    # 1970年からのミリ秒
    (r'(?<!\d)1[6-9]\d{11}(?!\d)',                   '<epoch>'),
    # ファイル名の日時印（朝_261124-2050.mp4 など）
    (r'(?<!\d)\d{6}-\d{4}(?!\d)',                    '<日時印>'),
    # 録画のバイト数（エンコーダの出力なので毎回わずかに違う）
    (r'"len":"\d+"',                                 '"len":"<バイト数>"'),
    (r'"bytes":\s*\d+',                              '"bytes":<バイト数>'),
]

def norm(s):
    for pat, rep in RULES:
        s = re.sub(pat, rep, s)
    return s

if __name__ == '__main__':
    sys.stdout.write(norm(sys.stdin.read()))
